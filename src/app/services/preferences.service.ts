import { Injectable, signal, PLATFORM_ID, inject, effect } from '@angular/core';
import { isPlatformBrowser } from '@angular/common';
import { HttpClient } from '@angular/common/http';
import { environment } from '../../environments/environment';
import { AuthService } from './auth.service';
import { firstValueFrom } from 'rxjs';

@Injectable({
  providedIn: 'root'
})
export class PreferencesService {
  private platformId = inject(PLATFORM_ID);
  private http = inject(HttpClient);
  private authService = inject(AuthService);
  private apiUrl = environment.apiUrl;

  historyHeroMovieId = signal<number | null>(null);
  favoritesHeroMovieId = signal<number | null>(null);
  hiddenFromGeneral = signal<string[]>([]); // Array of "{mediaType}_{mediaId}"

  // Nuove preferenze DB
  theme = signal<'dark' | 'light' | 'dynamic'>('dynamic');
  secondaryColor = signal<string>('yellow');
  glassBlur = signal<number>(28);
  glassOpacity = signal<number>(10);
  popupGlassBlur = signal<number>(24);
  popupGlassOpacity = signal<number>(8);
  globalBackgroundUrl = signal<string | null>(null);
  settingsBackgroundUrl = signal<string | null>(null);
  defaultCollectionId = signal<number | null>(null);
  collectionHeroModes = signal<Record<string, any>>({});
  notifyBell = signal<boolean>(true);
  notifyFavorites = signal<boolean>(true);
  notifyHistory = signal<boolean>(true);
  notifyRecommendations = signal<boolean>(true);
  notifyUpcoming = signal<boolean>(true);

  showOldBell = signal<boolean>(true);
  showOldFavorites = signal<boolean>(true);
  showOldHistory = signal<boolean>(true);
  showOldRecommendations = signal<boolean>(true);
  showOldUpcoming = signal<boolean>(true);

  autoplayTrailers = signal<boolean>(true); // obsolete but kept for safety if needed
  trailerAutoplay = signal<boolean>(true);
  trailerMute = signal<boolean>(false);
  trailerCaptions = signal<boolean>(false);
  trailerCaptionLang = signal<string>('it');
  trailerControls = signal<boolean>(true);

  appLanguage = signal<string>('it');
  defaultSeriesLanguage = signal<string>('it');
  defaultFilmLanguage = signal<string>('it');

  constructor() {
    effect(() => {
      const profile = this.authService.selectedProfile();
      if (profile && isPlatformBrowser(this.platformId)) {
        this.loadPreferences(profile.id);
      }
    });

    if (isPlatformBrowser(this.platformId)) {
      const savedHidden = localStorage.getItem('daisy-hidden-general');
      if (savedHidden) {
        try {
          this.hiddenFromGeneral.set(JSON.parse(savedHidden));
        } catch (e) { }
      }
    }
  }

  async loadPreferences(profileId: string) {
    try {
      const prefs = await firstValueFrom(this.http.get<any>(`${this.apiUrl}/preferences?profileId=${profileId}`));
      if (prefs) {
        this.theme.set(prefs.theme || 'dynamic');
        this.secondaryColor.set(prefs.secondary_color || 'yellow');
        this.glassBlur.set(prefs.glass_blur !== undefined ? prefs.glass_blur : 28);
        this.glassOpacity.set(prefs.glass_opacity !== undefined ? prefs.glass_opacity : 10);
        this.popupGlassBlur.set(prefs.popup_glass_blur !== undefined ? prefs.popup_glass_blur : 24);
        this.popupGlassOpacity.set(prefs.popup_glass_opacity !== undefined ? prefs.popup_glass_opacity : 8);
        this.globalBackgroundUrl.set(prefs.global_background_url || null);
        this.settingsBackgroundUrl.set(prefs.settings_background_url || null);
        this.defaultCollectionId.set(prefs.default_collection_id || null);
        this.collectionHeroModes.set(prefs.collection_hero_modes || {});
        this.notifyBell.set(prefs.notify_bell !== undefined ? prefs.notify_bell : true);
        this.notifyFavorites.set(prefs.notify_favorites !== undefined ? prefs.notify_favorites : true);
        this.notifyHistory.set(prefs.notify_history !== undefined ? prefs.notify_history : true);
        this.notifyRecommendations.set(prefs.notify_recommendations !== undefined ? prefs.notify_recommendations : true);
        this.notifyUpcoming.set(prefs.notify_upcoming !== undefined ? prefs.notify_upcoming : true);
        this.showOldBell.set(prefs.show_old_bell !== undefined ? prefs.show_old_bell : true);
        this.showOldFavorites.set(prefs.show_old_favorites !== undefined ? prefs.show_old_favorites : true);
        this.showOldHistory.set(prefs.show_old_history !== undefined ? prefs.show_old_history : true);
        this.showOldRecommendations.set(prefs.show_old_recommendations !== undefined ? prefs.show_old_recommendations : true);
        this.showOldUpcoming.set(prefs.show_old_upcoming !== undefined ? prefs.show_old_upcoming : true);
        this.autoplayTrailers.set(prefs.autoplay_trailers !== undefined ? prefs.autoplay_trailers : true);
        this.trailerAutoplay.set(prefs.trailer_autoplay !== undefined ? prefs.trailer_autoplay : true);
        this.trailerMute.set(prefs.trailer_mute !== undefined ? prefs.trailer_mute : false);
        this.trailerCaptions.set(prefs.trailer_captions !== undefined ? prefs.trailer_captions : false);
        this.trailerCaptionLang.set(prefs.trailer_caption_lang || 'it');
        this.trailerControls.set(prefs.trailer_controls !== undefined ? prefs.trailer_controls : true);
        this.appLanguage.set(prefs.app_language || 'it');
        this.defaultSeriesLanguage.set(prefs.default_series_language || 'it');
        this.defaultFilmLanguage.set(prefs.default_film_language || 'it');
        this.historyHeroMovieId.set(prefs.history_hero_movie_id || null);
        this.favoritesHeroMovieId.set(prefs.favorites_hero_movie_id || null);
      }
    } catch (err) {
      console.error('Error loading preferences', err);
    }
  }

  async savePreferences() {
    const profile = this.authService.selectedProfile();
    if (!profile) return;
    try {
      const prefs = {
        theme: this.theme(),
        secondary_color: this.secondaryColor(),
        glass_blur: this.glassBlur(),
        glass_opacity: this.glassOpacity(),
        popup_glass_blur: this.popupGlassBlur(),
        popup_glass_opacity: this.popupGlassOpacity(),
        global_background_url: this.globalBackgroundUrl(),
        settings_background_url: this.settingsBackgroundUrl(),
        default_collection_id: this.defaultCollectionId(),
        collection_hero_modes: this.collectionHeroModes(),
        notify_bell: this.notifyBell(),
        notify_favorites: this.notifyFavorites(),
        notify_history: this.notifyHistory(),
        notify_recommendations: this.notifyRecommendations(),
        notify_upcoming: this.notifyUpcoming(),
        show_old_bell: this.showOldBell(),
        show_old_favorites: this.showOldFavorites(),
        show_old_history: this.showOldHistory(),
        show_old_recommendations: this.showOldRecommendations(),
        show_old_upcoming: this.showOldUpcoming(),
        autoplay_next: true,
        autoplay_film: true,
        autoplay_trailers: true,
        trailer_autoplay: this.trailerAutoplay(),
        trailer_mute: this.trailerMute(),
        trailer_captions: this.trailerCaptions(),
        trailer_caption_lang: this.trailerCaptionLang(),
        trailer_controls: this.trailerControls(),
        app_language: this.appLanguage(),
        default_series_language: this.defaultSeriesLanguage(),
        default_film_language: this.defaultFilmLanguage(),
        history_hero_movie_id: this.historyHeroMovieId(),
        favorites_hero_movie_id: this.favoritesHeroMovieId()
      };
      await firstValueFrom(this.http.put(`${this.apiUrl}/preferences?profileId=${profile.id}`, prefs));
    } catch (err) {
      console.error('Error saving preferences', err);
    }
  }

  toggleHiddenFromGeneral(mediaKey: string) {
    this.hiddenFromGeneral.update(curr => {
      const newHidden = curr.includes(mediaKey) ? curr.filter(k => k !== mediaKey) : [...curr, mediaKey];
      if (isPlatformBrowser(this.platformId)) {
        localStorage.setItem('daisy-hidden-general', JSON.stringify(newHidden));
      }
      return newHidden;
    });
  }

  isHiddenFromGeneral(mediaKey: string): boolean {
    return this.hiddenFromGeneral().includes(mediaKey);
  }

  setHistoryHeroMovieId(id: number | null) {
    this.historyHeroMovieId.set(id);
    this.savePreferences();
  }

  setFavoritesHeroMovieId(id: number | null) {
    this.favoritesHeroMovieId.set(id);
    this.savePreferences();
  }
}
